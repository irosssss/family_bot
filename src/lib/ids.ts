/**
 * Генерация идентификаторов.
 *
 * Сейчас это обёртка над Date.now() — поведение совместимо с продом,
 * где id задач/наград/покупок уже формируются через Date.now().
 *
 * ⚠️ Известная проблема: коллизии при создании записей в одну миллисекунду.
 * Будет исправлено в Фазе 6 (переход на автоинкремент БД / атомарный счётчик),
 * когда источником правды станет PostgreSQL, а не in-memory appState.
 *
 * Используется в новых сервисах (Фаза 2+) вместо прямого Date.now().
 */
export function generateId(): number {
  return Date.now();
}
